function boltRect2(b, x, y0, y1, z0, z1) { // болты на грани, нормаль +X
  for (const y of [y0, 0, y1]) for (const z of [z0, z0 / 2, 0, z1 / 2, z1]) {
    if (y === 0 && z !== z0 && z !== z1) continue;
    b.at(M.T(0, y, z), () => b.cyl(x, x + 0.008, 0.011, 6));
  }
}

