// стенка через точки плана A,B=(x,z) на высоте y0. tilt>0 — верх завален внутрь, tilt<0 — нижний подрез
function wall(A, B, y0, tilt) {
  let nx = B[1] - A[1], nz = -(B[0] - A[0]); const l = Math.hypot(nx, nz); nx /= l; nz /= l;
  if (A[0] * nx + A[1] * nz < 0) { nx = -nx; nz = -nz; }
  const t = tilt * D2R;
  return plane([A[0], y0, A[1]], [nx * Math.cos(t), Math.sin(t), nz * Math.cos(t)]);
}
// План башни на уровне нижней кромки лобовых плит. Правая скула (s=+1) длиннее левой.
// A–B — лобовая плита скулы, B–D — борт (одна плоскость, сужается к корме), D–E — скос кормы.
function plan(s) {
  const cf = s > 0 ? 0.085 : 0;
  const zB = 1.52, zD = 1.14, xB = 1.20 + cf * 0.75, xD = -2.22, xC = -0.95;
  return { A: [1.72 + cf, MANT_HW * s], B: [xB, zB * s], C: [xC, (zB + (zD - zB) * (xB - xC) / (xB - xD)) * s], D: [xD, zD * s], E: [-2.34, 0.94 * s] };
}

