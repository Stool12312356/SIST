// ---------- мелкие детали ----------
function bolt(b, x, y, z, r = 0.012, h = 0.008) { // ось Y
  b.at(M.mul(M.T(x, y, z), AX_Y), () => b.cyl(0, h, r, 6));
}
function boltRect(b, x0, x1, y, z0, z1, step = 0.16, r = 0.011) {
  const nx = Math.max(1, Math.round((x1 - x0) / step)), nz = Math.max(1, Math.round((z1 - z0) / step));
  for (let i = 0; i <= nx; i++) { const x = x0 + (x1 - x0) * i / nx; bolt(b, x, y, z0, r); bolt(b, x, y, z1, r); }
  for (let i = 1; i < nz; i++) { const z = z0 + (z1 - z0) * i / nz; bolt(b, x0, y, z, r); bolt(b, x1, y, z, r); }
}
// скоба-ручка в плоскости: от a до b, вынос по d
function handle(b, a, c, d, r = 0.008) {
  b.pipe([a, V.add(a, d), V.add(c, d), c], r, 6);
}
// жалюзи: локально X — ширина, Y — высота, +Z — наружу
function grille(b, w, h, n, k = 0) {
  b.mat(DARK); b.bx(-w / 2 + 0.01, w / 2 - 0.01, -h / 2 + 0.01, h / 2 - 0.01, -0.012, 0.002, 0);
  b.mat(PAINT_S(k));
  const f = 0.035, d = 0.035;
  b.bx(-w / 2, w / 2, h / 2 - f, h / 2, -0.01, d); b.bx(-w / 2, w / 2, -h / 2, -h / 2 + f, -0.01, d);
  b.bx(-w / 2, -w / 2 + f, -h / 2, h / 2, -0.01, d); b.bx(w / 2 - f, w / 2, -h / 2, h / 2, -0.01, d);
  const hh = h - 2 * f, st = hh / n;
  for (let i = 0; i < n; i++) {
    const y = -hh / 2 + (i + 0.5) * st;
    b.at(M.mul(M.T(0, y, 0.014), M.RX(-38 * D2R)), () => b.box(0, 0, 0, w - 2 * f + 0.01, st * 0.92, 0.006, 0.0015));
  }
  if (w > 0.9) b.bx(-0.012, 0.012, -h / 2, h / 2, -0.005, d + 0.004);
}

