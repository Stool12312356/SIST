// ---------- материалы ----------
const TAN = [0.685, 0.605, 0.468];           // CARC Tan 686A
const shade = (k) => TAN.map((c) => c * (1 + 2.6 * k));
const PAINT = (k = 0) => ({ color: shade(k), rough: 0.80, metal: 0, dust: 0.85, bump: 1 });
